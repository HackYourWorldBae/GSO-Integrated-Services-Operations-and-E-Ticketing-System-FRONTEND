/**
 * Session Synchronization Utility — Cross-Tab Authentication Integrity
 *
 * Implements the industry-standard multi-tab synchronization protocol using
 * BroadcastChannel (with localStorage event fallback) to guarantee that:
 *
 * 1. Only ONE authenticated identity is active in a browser profile at any time.
 * 2. Logging in on any tab immediately synchronizes all other open tabs.
 * 3. Logging out on any tab immediately ends sessions on all other open tabs.
 * 4. Account/Role switches in another tab notify and redirect open tabs away from
 *    unauthorized paths without session bleeding or state desynchronization.
 */

const CHANNEL_NAME = 'gso_auth_channel';
const STORAGE_SYNC_KEY = '__gso_session_sync__';

let broadcastChannel = null;
let lastProcessedTimestamp = 0;

/**
 * Get or initialize BroadcastChannel safely across modern browsers and SSR/test environments.
 */
function getBroadcastChannel() {
  if (broadcastChannel) return broadcastChannel;
  const ChannelClass =
    (typeof window !== 'undefined' && window.BroadcastChannel) ||
    (typeof globalThis !== 'undefined' && globalThis.BroadcastChannel);

  if (typeof ChannelClass === 'function') {
    try {
      broadcastChannel = new ChannelClass(CHANNEL_NAME);
    } catch {
      broadcastChannel = null;
    }
  }
  return broadcastChannel;
}

export function _resetChannelForTesting() {
  if (broadcastChannel && typeof broadcastChannel.close === 'function') {
    try { broadcastChannel.close(); } catch {}
  }
  broadcastChannel = null;
  lastProcessedTimestamp = 0;
}

/**
 * Broadcast an authentication event to all other tabs in the same origin.
 *
 * @param {'AUTH_LOGIN' | 'AUTH_LOGOUT' | 'AUTH_SESSION_CHANGED'} type
 * @param {object} payload
 */
export function broadcastAuthEvent(type, payload = {}) {
  if (typeof window === 'undefined') return;

  const eventData = {
    type,
    ...payload,
    timestamp: Date.now(),
    tabId: window.__gso_tab_id || (window.__gso_tab_id = Math.random().toString(36).slice(2, 9)),
  };

  // 1. Primary: BroadcastChannel (low latency, doesn't pollute storage)
  const channel = getBroadcastChannel();
  if (channel) {
    try {
      channel.postMessage(eventData);
    } catch {
      // Non-fatal, fallback to localStorage
    }
  }

  // 2. Secondary fallback: localStorage storage event (cross-tab across all browser engines)
  try {
    localStorage.setItem(STORAGE_SYNC_KEY, JSON.stringify(eventData));
  } catch {
    // Non-fatal if storage quota exceeded or disabled
  }
}

/**
 * Set up listeners for auth synchronization events from other tabs.
 *
 * @param {object} handlers
 * @param {Function} [handlers.onLogin]
 * @param {Function} [handlers.onLogout]
 * @param {Function} [handlers.onSessionChanged]
 * @returns {Function} Teardown/cleanup function
 */
export function setupCrossTabSessionSync(handlers = {}) {
  if (typeof window === 'undefined') return () => {};

  const currentTabId = window.__gso_tab_id || (window.__gso_tab_id = Math.random().toString(36).slice(2, 9));

  const processIncomingEvent = (eventData) => {
    if (!eventData || typeof eventData !== 'object') return;

    // Ignore events generated by this exact tab
    if (eventData.tabId && eventData.tabId === currentTabId) {
      return;
    }

    // Deduplicate events that might arrive via both BroadcastChannel and storage listener
    if (eventData.timestamp && eventData.timestamp <= lastProcessedTimestamp) {
      return;
    }
    lastProcessedTimestamp = eventData.timestamp || Date.now();

    switch (eventData.type) {
      case 'AUTH_LOGIN':
        handlers.onLogin?.(eventData);
        break;
      case 'AUTH_LOGOUT':
        handlers.onLogout?.(eventData);
        break;
      case 'AUTH_SESSION_CHANGED':
        handlers.onSessionChanged?.(eventData);
        break;
      default:
        break;
    }
  };

  // 1. BroadcastChannel Listener
  const channel = getBroadcastChannel();
  const channelHandler = (event) => {
    processIncomingEvent(event.data);
  };

  if (channel) {
    channel.addEventListener('message', channelHandler);
  }

  // 2. Storage Event Listener (triggers only in OTHER tabs when localStorage changes)
  const storageHandler = (event) => {
    if (event.key === STORAGE_SYNC_KEY && event.newValue) {
      try {
        const parsed = JSON.parse(event.newValue);
        processIncomingEvent(parsed);
      } catch {
        // Ignore parse errors
      }
    }
  };

  window.addEventListener('storage', storageHandler);

  return () => {
    if (channel) {
      channel.removeEventListener('message', channelHandler);
    }
    window.removeEventListener('storage', storageHandler);
  };
}
