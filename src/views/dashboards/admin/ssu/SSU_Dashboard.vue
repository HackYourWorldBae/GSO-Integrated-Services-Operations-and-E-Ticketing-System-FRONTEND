<script setup>
import { onMounted, ref, nextTick } from 'vue';
import MainLayout from '@/layouts/Main_Dashboard_Layout.vue';
import Chart from 'chart.js/auto';
import api from '@/api/client';

const stats = ref({});

const ssuActivePeriod = ref('Month');
const ssuPeriodFilters = [
  { key: 'Day',   label: 'This Day' },
  { key: 'Week',  label: 'This Week' },
  { key: 'Month', label: 'This Month' },
  { key: 'Year',  label: 'This Year' }
];

let ssuServiceFreqChart = null;
let charts = [];

function setSsuPeriod(period) {
  ssuActivePeriod.value = period;
  if (ssuServiceFreqChart && stats.value.service_freq) {
    const data = stats.value.service_freq[period] || [];
    ssuServiceFreqChart.data.labels = data.map(d => d.service_type);
    ssuServiceFreqChart.data.datasets[0].data = data.map(d => parseInt(d.count));
    ssuServiceFreqChart.update();
  }
}

const renderCharts = () => {
  // Destroy existing charts to prevent memory leaks if re-rendered
  charts.forEach(c => c.destroy());
  charts = [];

  const safeVal = (val) => parseFloat(val) || 0;

  const formatReason = (code) => {
    if (!code) return 'None';
    const map = {
      personnelAbsent: "Personnel Absent",
      extendedBreak: "Extended Break Period",
      additionalWork: "Additional Work",
      lackWorkingDays: "Lack of Working Days",
      lackMaterials: "Lack of Materials / Tools",
      lackSkills: "Lack of Skills"
    };
    return map[code] || code.replace(/([A-Z])/g, ' $1').replace(/^./, str => str.toUpperCase());
  };

  // 1. Incident Heatmap Doughnut
  const incidentCtx = document.getElementById('incidentDoughnut');
  if (incidentCtx && stats.value.incident_heatmap) {
    const data = stats.value.incident_heatmap;
    charts.push(new Chart(incidentCtx, {
      type: 'doughnut',
      data: {
        labels: data.map(d => d.category),
        datasets: [{
          data: data.map(d => parseInt(d.count)),
          backgroundColor: ['#ef4444', '#f97316', '#f59e0b', '#10b981', '#3b82f6', '#8b5cf6', '#ec4899'],
          hoverOffset: 15, borderRadius: 10, borderWidth: 4, borderColor: '#ffffff'
        }]
      },
      options: {
        plugins: { legend: { position: 'bottom' } },
        cutout: '65%', responsive: true, maintainAspectRatio: false
      }
    }));
  }

  // 2. Vehicle Pass Pipeline
  const passCtx = document.getElementById('passPipelineChart');
  if (passCtx && stats.value.pass_pipeline) {
    const data = stats.value.pass_pipeline;
    const statuses = ['pending', 'approved', 'resolved', 'cancelled'];
    const formatStatus = (s) => s.charAt(0).toUpperCase() + s.slice(1);
    
    const counts = statuses.map(s => {
      const match = data.find(d => d.status === s);
      return match ? parseInt(match.count) : 0;
    });

    charts.push(new Chart(passCtx, {
      type: 'bar',
      data: {
        labels: statuses.map(formatStatus),
        datasets: [{
          label: 'Tickets',
          data: counts,
          backgroundColor: ['#f59e0b', '#3b82f6', '#10b981', '#ef4444'],
          borderRadius: 6
        }]
      },
      options: { 
        indexAxis: 'y', 
        plugins: { legend: { display: false } }, 
        responsive: true, maintainAspectRatio: false 
      }
    }));
  }

  // 5. Service Request Frequency
  const freqCtx = document.getElementById('fgmuServiceFreqChart') || 
                  document.getElementById('leauServiceFreqChart') || 
                  document.getElementById('ssuServiceFreqChart') || 
                  document.getElementById('tasuServiceFreqChart');
  if (freqCtx && stats.value.service_freq) {
    const initData = stats.value.service_freq[ssuActivePeriod.value] || [];
    ssuServiceFreqChart = new Chart(freqCtx, {
      type: 'bar',
      data: {
        labels: initData.map(d => d.service_type),
        datasets: [{
          label: 'Requests',
          data: initData.map(d => parseInt(d.count)),
          backgroundColor: ['#059669', '#10b981', '#34d399', '#6ee7b7', '#a7f3d0'],
          borderRadius: 8
        }]
      },
      options: { plugins: { legend: { display: false } }, responsive: true, maintainAspectRatio: false }
    });
    charts.push(ssuServiceFreqChart);
  }
};

const fetchStats = async () => {
  try {
    const response = await api.get('tickets/stats/SSU');
    if (response.data?.data?.stats) {
      stats.value = response.data.data.stats;
      nextTick(() => {
        renderCharts();
      });
    }
  } catch (error) {
    console.error('Failed to fetch SSU stats:', error);
  }
};

onMounted(() => {
  fetchStats();
});
